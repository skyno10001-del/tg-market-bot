function todayISO() {
  return new Date().toISOString().slice(0, 10);
}

export function buildMessage({ job }) {
  const d = todayISO();

  if (job === "overseas") {
    return [
      `🌎 <b>해외시장 요약</b> (${d})`,
      ``,
      `- 나스닥 / S&P500 / 다우: (데이터 자리)`,
      `- 금리/달러: (데이터 자리)`,
      ``,
      `<b>전략가 코멘트</b>:`,
      `조건 충족 전까지 추격보다 구조 확인 우선.`
    ].join("\n");
  }

  if (job === "premarket") {
    return [
      `🕘 <b>장전 전략 브리핑</b> (${d})`,
      ``,
      `1) 오늘 시장 모드: (추세/순환/관망)`,
      `2) 주도 섹터 후보: (1~2개)`,
      `3) 단기 유리 패턴: (돌파/눌림/수렴)`,
      `4) 오늘 금지 행동: (추격/역추세)`,
      ``,
      `<b>전략가 코멘트</b>:`,
      `확정이 아니라 조건. 확인 후 접근.`
    ].join("\n");
  }

  if (job === "midday") {
    return [
      `🕦 <b>오전 수급/흐름</b> (${d})`,
      ``,
      `- 외인/기관: (데이터 자리)`,
      `- 거래대금 상위: (데이터 자리)`,
      ``,
      `<b>전략가 코멘트</b>:`,
      `오전 흐름이 ‘추세’인지 ‘순환’인지 구분 필요.`
    ].join("\n");
  }

  if (job === "close") {
    return [
      `🕒 <b>마감 자금 이동 정리</b> (${d})`,
      ``,
      `오전 → (섹터)`,
      `오후 → (섹터)`,
      ``,
      `1) 오늘 자금 성격: (추세/순환)`,
      `2) 거래대금: (증가/감소)`,
      `3) 내일 포인트: (1~2개)`,
      ``,
      `<b>전략가 결론</b>:`,
      `내일은 추격보다 패턴 완성 종목 ‘확인 후’ 접근.`
    ].join("\n");
  }

  return `ℹ️ job=${job} (${d})`;
}